#!/usr/bin/env bash
# CICLONE: verila o RTL REAL do core SMS (verilog/sd2snes_sms: sms_core.v + sms.v + sms_translate.v
# + psg.v + tv80/) para o C++ que o modelo do FPGA roda quando o firmware carrega o fpga_sms.
# A cola do main.v/address.v (árbitro da PSRAM, double buffer, pad, CE de 3,58 MHz, janela
# $E0-$E3) fica em C++ no fpga_model/sms_model.cpp.
#   bash fpga_model/verilate_sms.sh           (árvore: CICLONE_SMS_RTL, senão CICLONE_TREE, senão extern/sd2snes)
# Saída: build/vsms/ (Vsms_core__ALL.a + verilated*.o). Só reverila quando um .v mudou.
set -e
cd "$(dirname "$0")/.."
TREE="${CICLONE_TREE:-extern/sd2snes}"
SMS="${CICLONE_SMS_RTL:-$TREE/verilog/sd2snes_sms}"
OUT="${CICLONE_VSMS:-${CICLONE_BUILD:-build}/vsms}"
[ -f "$SMS/sms_core.v" ] || { echo "sem $SMS/sms_core.v (CICLONE_SMS_RTL / CICLONE_TREE)"; exit 1; }
SMS="$(cd "$SMS" && pwd)"
mkdir -p "$OUT"
# carimbo: caminho + conteúdo dos .v; igual ao da última build = nada a fazer
STAMP="$( (echo "$SMS"; cat "$SMS"/*.v "$SMS"/tv80/*.v fpga_model/verilate_sms.sh) | shasum | cut -c1-16)"
if [ -f "$OUT/STAMP" ] && [ "$(cat "$OUT/STAMP")" = "$STAMP" ] && [ -f "$OUT/Vsms_core__ALL.a" ]; then
  echo "OK: $OUT em dia ($SMS)"; exit 0
fi
rm -rf "$OUT"; mkdir -p "$OUT"
nice verilator --cc --build -j "${VJOBS:-4}" --top-module sms_core +define+MK3 \
  -O3 --x-assign fast --x-initial fast -CFLAGS "-O2" \
  -Wno-fatal -Wno-lint -Wno-style -Wno-WIDTH -Wno-UNOPTFLAT -Wno-BLKANDNBLK -Wno-PINMISSING \
  -Wno-MULTIDRIVEN -Wno-COMBDLY -Wno-CASEINCOMPLETE \
  -I"$SMS" -y "$SMS" -y "$SMS/tv80" --Mdir "$OUT" "$SMS/sms_core.v" >"$OUT/verilator.log" 2>&1 \
  || { tail -30 "$OUT/verilator.log"; exit 1; }
# the posedge detectors of CLK (sms_model.cpp lowers them by hand instead of a 2nd eval);
# none found (another Verilator) = the canonical two evals per cycle
PREV="$(grep -ho '(~ (IData)(vlSelfRef.__Vtrigprevexpr___TOP__CLK__[0-9]*))' "$OUT"/Vsms_core___024root__*.cpp \
        | grep -o '__Vtrigprevexpr___TOP__CLK__[0-9]*' | sort -u)"
{ echo "// generated by verilate_sms.sh"
  if [ -n "$PREV" ]; then
    echo "#define VSMS_CLK_FALL(r) do { \\"
    for p in $PREV; do echo "  (r)->$p = 0; \\"; done
    echo "} while (0)"
  else
    echo "#define CICLONE_SMS_SAFE_EVAL 1"
  fi
} > "$OUT/vsms_clk.h"
# the core's big memories (VRAM, WRAM...): left out of the fixed-point compare of sms_model.cpp
BIG="$(grep -o 'VlUnpacked<[A-Za-z]*/\*[0-9:]*\*/, [0-9]*> [A-Za-z0-9_]*;' "$OUT/Vsms_core___024root.h" \
       | awk '{n=$2; sub(">","",n); if (n+0 > 256) { m=$3; sub(";","",m); print m } }')"
{ echo "// generated by verilate_sms.sh"
  printf '#define VSMS_BIG_MEMBERS(X)'
  for b in $BIG; do printf ' X(%s)' "$b"; done
  echo
} > "$OUT/vsms_snap.h"
# the core's memories by name, for `smspeek` (vram cram wram vreg) and the Sega mapper's banks
{ echo "// generated by verilate_sms.sh"
  printf '#define VSMS_MEMS(X)'
  for n in vram cram wram vreg; do
    m="$(grep -o "VlUnpacked<[A-Za-z]*/\\*7:0\\*/, [0-9]*> [A-Za-z0-9_]*__DOT__u_sms__DOT__$n;" "$OUT/Vsms_core___024root.h" | awk '{print $3}' | tr -d ';' | head -1)"
    [ -n "$m" ] && printf ' X(%s, %s)' "$n" "$m"
  done
  echo
  printf '#define VSMS_BANKS(X)'
  for n in bk_ctrl bk0 bk1 bk2; do
    grep -q "CData/\*7:0\*/ sms_core__DOT__u_sms__DOT__$n;" "$OUT/Vsms_core___024root.h" && printf ' X(sms_core__DOT__u_sms__DOT__%s)' "$n"
  done
  echo
} > "$OUT/vsms_mem.h"
# main.v's glue is mirrored in sms_model.cpp; variants of it it knows are recognised here
MAINV="$SMS/main.v"
{ echo "// generated by verilate_sms.sh from $MAINV"
  grep -q 'BUS_RDY(1'"'"'b0)' "$MAINV" 2>/dev/null && echo "#define VSMS_GLUE_CTX_OFF 1"
  grep -q 'sms_rd_last' "$MAINV" 2>/dev/null && echo "#define VSMS_GLUE_FAIR 1"
  grep -q '&DBG_SWAP,' "$OUT/Vsms_core.h" && echo "#define VSMS_PORT_DBG_SWAP 1"
  true
} > "$OUT/vsms_glue.h"
echo "$STAMP" > "$OUT/STAMP"
echo "$SMS" > "$OUT/SRC"
echo "OK: $OUT (Vsms_core) <- $SMS"
